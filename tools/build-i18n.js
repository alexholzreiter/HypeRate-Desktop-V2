#!/usr/bin/env node
// Turns src/i18n/*.json into src/i18n/strings.js, which both the main process (require) and the
// windows (<script src>) can load. The JSON files are what translators edit: one file per
// language, the same keys in each, English as the reference every other language falls back to.
//
//   npm run i18n           rebuild strings.js
//   npm run i18n -- check  only report keys that are missing or extra compared with English
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'src', 'i18n');
const OUT = path.join(DIR, 'strings.js');
const REFERENCE = 'en';

const languages = fs.readdirSync(DIR)
  .filter((f) => f.endsWith('.json'))
  .map((f) => path.basename(f, '.json'))
  .sort((a, b) => (a === REFERENCE ? -1 : b === REFERENCE ? 1 : a.localeCompare(b)));

const strings = {};
for (const lang of languages) {
  strings[lang] = JSON.parse(fs.readFileSync(path.join(DIR, lang + '.json'), 'utf8'));
}
if (!strings[REFERENCE]) throw new Error(`src/i18n/${REFERENCE}.json is missing`);

// Flat "section.key" paths, so nested sections are compared too
function paths(obj, prefix = '') {
  return Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' ? paths(v, prefix + k + '.') : [prefix + k]);
}

const reference = new Set(paths(strings[REFERENCE]));
let problems = 0;
for (const lang of languages.filter((l) => l !== REFERENCE)) {
  const own = new Set(paths(strings[lang]));
  const missing = [...reference].filter((p) => !own.has(p));
  const extra = [...own].filter((p) => !reference.has(p));
  if (missing.length) console.log(`${lang}: ${missing.length} missing (English is shown instead): ${missing.join(', ')}`);
  if (extra.length) console.log(`${lang}: ${extra.length} not in English: ${extra.join(', ')}`);
  problems += missing.length + extra.length;
}

if (process.argv[2] === 'check') {
  console.log(problems ? `${problems} differences` : `${languages.join(', ')}: all keys match`);
  process.exit(problems ? 1 : 0);
}

const body = `// Generated by tools/build-i18n.js from src/i18n/*.json — do not edit by hand.
// Edit the JSON files and run: npm run i18n
(function (root) {
  var STRINGS = ${JSON.stringify(strings, null, 2)};
  if (typeof module !== 'undefined' && module.exports) module.exports = STRINGS;
  else root.HR_STRINGS = STRINGS;
})(this);
`;
fs.writeFileSync(OUT, body);
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${languages.join(', ')})`);
